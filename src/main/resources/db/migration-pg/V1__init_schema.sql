-- ========== audit_logs（V8）==========
CREATE TABLE IF NOT EXISTS audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator    VARCHAR(100) NOT NULL,
    action      VARCHAR(100) NOT NULL,
    target_type VARCHAR(50),
    target_id   VARCHAR(64),
    detail      VARCHAR(500),
    success     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_operator   ON audit_logs (operator);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_logs (created_at);

-- ========== coupons / user_coupons（V9）==========
CREATE TABLE IF NOT EXISTS coupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40)   NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    discount_amount DECIMAL(12,2) NOT NULL,
    min_amount      DECIMAL(12,2) NOT NULL DEFAULT 0,
    total_quantity  INT           NOT NULL DEFAULT 0,
    issued_count    INT           NOT NULL DEFAULT 0,
    per_user_limit  INT           NOT NULL DEFAULT 1,
    start_at        TIMESTAMP(6)  NOT NULL,
    end_at          TIMESTAMP(6)  NOT NULL,
    enabled         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_coupons_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS user_coupons (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id     BIGINT       NOT NULL,
    username      VARCHAR(100) NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'unused',
    used_order_id BIGINT,
    claimed_at    TIMESTAMP(6) NOT NULL,
    used_at       TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_user_coupons_user   ON user_coupons (username);
CREATE INDEX IF NOT EXISTS idx_user_coupons_coupon ON user_coupons (coupon_id);
