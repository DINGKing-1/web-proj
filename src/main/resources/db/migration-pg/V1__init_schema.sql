-- V1: PostgreSQL 全量初始化（腾讯云托管 / profile=pg）
-- 本脚本 = MySQL 侧 V1~V22 合并后的表结构终态，只用于全新 PG 库；
-- 本地 MySQL 继续走 classpath:db/migration（V1~V22），两套目录勿混用。
-- 与 JPA 实体对齐，ddl-auto=validate 依赖此基线。

-- ========== users（V1+V4+V15+V21+V22）==========
CREATE TABLE IF NOT EXISTS users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username               VARCHAR(100)  NOT NULL,
    password               VARCHAR(255)  NOT NULL,
    email                  VARCHAR(100),
    phone                  VARCHAR(20),
    nickname               VARCHAR(100),
    role                   VARCHAR(20)   NOT NULL,
    balance                DECIMAL(12,2) NOT NULL,
    avatar                 VARCHAR(255)  NOT NULL,
    session_id             VARCHAR(100),
    created_at             TIMESTAMP(6)  NOT NULL,
    last_active_time       TIMESTAMP(6),
    banned                 BOOLEAN       NOT NULL,
    deleted                BOOLEAN       NOT NULL DEFAULT FALSE,
    deleted_at             TIMESTAMP(6),
    deleted_by             VARCHAR(20),
    must_change_password   BOOLEAN       NOT NULL DEFAULT FALSE,
    payment_password       VARCHAR(255),
    preferred_payment      VARCHAR(20)   NOT NULL DEFAULT 'balance',
    gender                 VARCHAR(10)   NOT NULL DEFAULT 'secret',
    birthday               DATE,
    CONSTRAINT uk_users_username UNIQUE (username)
);

-- ========== products（V1+V6+V13+V20）==========
CREATE TABLE IF NOT EXISTS products (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255)  NOT NULL,
    category           VARCHAR(255)  NOT NULL,
    description        TEXT,
    original_price     DECIMAL(12,2) NOT NULL,
    second_hand_price  DECIMAL(12,2) NOT NULL,
    item_condition     VARCHAR(255)  NOT NULL,
    seller_name        VARCHAR(255)  NOT NULL,
    seller_phone       VARCHAR(255),
    seller_username    VARCHAR(100),
    seller_avatar      VARCHAR(255),
    image_url          TEXT,
    quantity           INT           NOT NULL,
    status             VARCHAR(255)  NOT NULL,
    view_count         INT           NOT NULL,
    created_at         TIMESTAMP(6)  NOT NULL,
    review_note        VARCHAR(255),
    reserved_quantity  INT           NOT NULL DEFAULT 0,
    version            BIGINT        NOT NULL DEFAULT 0
);

-- ========== orders（V1+V7+V9+V12+V16+V18+V19）==========
-- 注：V17 曾把 pay_exception 建为 VARCHAR，V18 改为 BIT(1)；实体为 Boolean，PG 用 BOOLEAN。
CREATE TABLE IF NOT EXISTS orders (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number             VARCHAR(30)   NOT NULL,
    username                 VARCHAR(255)  NOT NULL,
    product_id               BIGINT        NOT NULL,
    seller_username          VARCHAR(100),
    product_name             VARCHAR(255)  NOT NULL,
    product_price            DECIMAL(12,2) NOT NULL,
    quantity                 INT           NOT NULL,
    category                 VARCHAR(255)  NOT NULL,
    image_url                TEXT          NOT NULL,
    receiver_name            VARCHAR(255)  NOT NULL,
    receiver_phone           VARCHAR(255)  NOT NULL,
    receiver_address         TEXT          NOT NULL,
    payment_method           VARCHAR(255)  NOT NULL,
    status                   VARCHAR(255)  NOT NULL,
    tracking_number          VARCHAR(100),
    rating                   INT,
    review_content           VARCHAR(500),
    reviewed_at              TIMESTAMP(6),
    after_sale_reason        VARCHAR(200),
    prev_status              VARCHAR(20),
    seller_paid              BOOLEAN       NOT NULL,
    received_at              TIMESTAMP(6),
    shipped_at               TIMESTAMP(6),
    created_at               TIMESTAMP(6)  NOT NULL,
    return_tracking_number   VARCHAR(100),
    after_sale_at            TIMESTAMP(6),
    return_sent_at           TIMESTAMP(6),
    discount_amount          DECIMAL(12,2),
    return_approved_at       TIMESTAMP(6),
    admin_cancel_reason      VARCHAR(512),
    pay_exception            BOOLEAN,
    pay_exception_reason     VARCHAR(255),
    CONSTRAINT uk_orders_order_number UNIQUE (order_number)
);

-- ========== cart_items / comments / favorites / addresses（V1）==========
CREATE TABLE IF NOT EXISTS cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL,
    product_id BIGINT       NOT NULL,
    quantity   INT          NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL,
    user_name  VARCHAR(255) NOT NULL,
    content    TEXT         NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS favorites (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(100) NOT NULL,
    product_id BIGINT       NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS addresses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    receiver_name VARCHAR(255) NOT NULL,
    phone         VARCHAR(255) NOT NULL,
    province      VARCHAR(255) NOT NULL,
    city          VARCHAR(255) NOT NULL,
    district      VARCHAR(255) NOT NULL,
    detail        VARCHAR(255) NOT NULL,
    is_default    BOOLEAN      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL
);

-- ========== chat_rooms（V1+V11+V14）==========
CREATE TABLE IF NOT EXISTS chat_rooms (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1username     VARCHAR(100) NOT NULL,
    user2username     VARCHAR(100) NOT NULL,
    product_id        BIGINT       NOT NULL,
    last_message      VARCHAR(500),
    last_message_time TIMESTAMP(6) NOT NULL,
    user1unread       INT          NOT NULL,
    user2unread       INT          NOT NULL,
    room_type         VARCHAR(20)  NOT NULL,
    deleted           BOOLEAN      NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    deleted_by_user1  BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_by_user2  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_chat_rooms_pair UNIQUE (user1username, user2username, product_id, room_type)
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT       NOT NULL,
    sender_username VARCHAR(100) NOT NULL,
    product_id      BIGINT,
    content         TEXT         NOT NULL,
    message_type    VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL
);

-- ========== notifications（V1）==========
