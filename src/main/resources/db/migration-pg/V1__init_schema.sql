);

-- ========== quick_replies / wallet_transactions / announcements / withdraw_requests（V1）==========
CREATE TABLE IF NOT EXISTS quick_replies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category   VARCHAR(50),
    title      VARCHAR(200) NOT NULL,
    content    TEXT         NOT NULL,
    sort_order INT          NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(100)  NOT NULL,
    type       VARCHAR(20)   NOT NULL,
    title      VARCHAR(200),
    amount     DECIMAL(12,2) NOT NULL,
    status     VARCHAR(20),
    created_at TIMESTAMP(6)  NOT NULL
);

CREATE TABLE IF NOT EXISTS announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(100) NOT NULL,
    content    VARCHAR(500),
    type       VARCHAR(20)  NOT NULL,
    image_url  VARCHAR(500),
    link_url   VARCHAR(500),
    sort_order INT          NOT NULL,
    enabled    BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS withdraw_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(100)  NOT NULL,
    amount         DECIMAL(12,2) NOT NULL,
    account        VARCHAR(200)  NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    reject_reason  VARCHAR(200),
    processed_at   TIMESTAMP(6),
    processed_by   VARCHAR(100),
    created_at     TIMESTAMP(6)  NOT NULL
);

-- ========== offers（V3）==========
CREATE TABLE IF NOT EXISTS offers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT        NOT NULL,
    product_name    VARCHAR(255)  NOT NULL,
    image_url       VARCHAR(255),
    buyer_username  VARCHAR(100)  NOT NULL,
    seller_username VARCHAR(100)  NOT NULL,
    offer_price     DECIMAL(12,2) NOT NULL,
    message         VARCHAR(200),
    status          VARCHAR(20)   NOT NULL,
    order_id        BIGINT,
    created_at      TIMESTAMP(6)  NOT NULL,
    responded_at    TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS idx_offers_buyer  ON offers (buyer_username);
CREATE INDEX IF NOT EXISTS idx_offers_seller ON offers (seller_username);
CREATE INDEX IF NOT EXISTS idx_offers_product ON offers (product_id);

